import type { RichContent } from '../../shared/types';
import type { FormulaCategoryId, StudyContentBlock, StudyTrackId } from '../study/types';

export type PracticeDifficulty = 'easy' | 'medium' | 'exam';
export type PracticeQuestionKind = 'choice' | 'short_answer';
export type PracticeSessionMode = 'quick' | 'category' | 'formula' | 'mistakes' | 'ai';

export type PracticeChoice = {
  label: string;
  spoken?: string;
};

export type PracticeQuestion = {
  id: string;
  title: string;
  category: FormulaCategoryId;
  tracks: readonly StudyTrackId[];
  difficulty: PracticeDifficulty;
  formulaId: string;
  kind: PracticeQuestionKind;
  prompt: readonly StudyContentBlock[];
  /** Exactly 4 choices when kind === 'choice'. */
  choices?: readonly [PracticeChoice, PracticeChoice, PracticeChoice, PracticeChoice];
  /** Index 0..3 of the single verified answer when kind === 'choice'. */
  correctIndex?: 0 | 1 | 2 | 3;
  /** Accepted normalized forms when kind === 'short_answer'. */
  acceptedAnswers?: readonly string[];
  /** Human-readable canonical answer displayed after grading. */
  answerDisplay: string;
  /** Short placeholder/hint shown inside the answer input for short_answer items. */
  inputHint?: string;
  /** Gentle one-line nudge shown on demand before answering. */
  hint: string;
  /** Step-by-step worked solution rendered with MathJax Fira SVG. */
  explanation: readonly StudyContentBlock[];
  /**
   * Optional editor-compatible LaTeX expression accepted by parseMathInput so
   * students can open a full AI lesson in MathProcessing directly.
   */
  editorLatex?: string;
  /** True when dynamically generated by generatePracticeExercise. */
  aiGenerated?: boolean;
  /** Pre-rendered RichContent supplied directly by the AI backend. */
  renderedPrompt?: RichContent;
  renderedExplanation?: RichContent;
};

export type PracticeSessionAnswerRecord = {
  questionId: string;
  title: string;
  category: FormulaCategoryId;
  formulaId: string;
  correct: boolean;
  userAnswerLabel: string;
  correctAnswerLabel: string;
};

export type PracticeSessionRecord = {
  id: string;
  completedAt: string;
  mode: PracticeSessionMode;
  track: StudyTrackId;
  category?: FormulaCategoryId;
  correctCount: number;
  totalCount: number;
  elapsedSeconds: number;
};

